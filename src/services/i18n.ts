export function translate(key: string, lang: Language, fallback?: string): string {
  const dict = TRANSLATIONS[lang];
  if (dict && dict[key]) {
    return dict[key];
  }
  const enDict = TRANSLATIONS.EN;
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  return fallback || key;
}
